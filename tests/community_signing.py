class SigningPolicy(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory(prefix='bttv-signing-policy-')
        self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name).resolve();self.output=self.root/'export'
        # These deliberately invalid non-key/non-APK bytes can never sign an APK.
        self.key=self.root/'external.fixture';self.key.write_bytes(b'NOT_A_KEYSTORE')
        self.password=self.root/'input.fixture';self.password.write_bytes(b'NON_SECRET_TEST_SENTINEL')
        self.apk=self.root/'unsigned.fixture';self.apk.write_bytes(b'NOT_AN_APK')
        self.source=self.root/'input.bundle.fixture';self.source.write_bytes(b'NOT_A_TWITCH_BUNDLE')
        self.env=dict(KS=str(self.key),KSPASS_FILE=str(self.password),EXPECTED_SIGNER_SHA256='A'*64)

    def config(self,changes=None):
        return signer.signing_config(dict(self.env,**(changes or {})),self.output)

    def test_external_password_file_and_fixed_identity(self):
        key,source,pin=self.config()
        self.assertEqual(key,self.key);self.assertEqual(source,'file:'+str(self.password));self.assertEqual(pin,'A'*64)

    def test_environment_reference_never_contains_password_value(self):
        _,source,_=self.config(dict(KSPASS_FILE='',KSPASS='NON_SECRET_TEST_SENTINEL'))
        self.assertEqual(source,'env:KSPASS')
        self.assertNotIn('NON_SECRET_TEST_SENTINEL',source)

    def test_missing_ambiguous_passwords_rejected(self):
        for change in [dict(KSPASS_FILE=''),dict(KSPASS='NON_SECRET_TEST_SENTINEL')]:
            with self.subTest(change=change),self.assertRaises(ValueError):self.config(change)

    def test_certificate_pin_required_and_test_certificate_forbidden(self):
        for pin in ['', 'A'*63, 'Z'*64, signer.TEST_SIGNER, signer.TEST_SIGNER.lower()]:
            with self.subTest(pin=pin),self.assertRaises(ValueError):self.config(dict(EXPECTED_SIGNER_SHA256=pin))

    def test_keystore_must_exist_be_absolute_and_outside_git(self):
        for path in ['relative.fixture',str(self.root/'absent'),str(ROOT/'bttv.manifest.json')]:
            with self.subTest(path=path),self.assertRaises(ValueError):self.config(dict(KS=path))

    def test_password_file_outside_git_and_not_an_output(self):
        with self.assertRaises(ValueError):self.config(dict(KSPASS_FILE=str(ROOT/'README.md')))
        self.output.mkdir();p=self.output/'private.fixture';p.write_bytes(b'NON_SECRET_TEST_SENTINEL')
        with self.assertRaises(ValueError):self.config(dict(KSPASS_FILE=str(p)))

    def test_password_line_validation(self):
        for raw in [b'',b'\xef\xbb\xbfX',b'\xff',b'a\nb',b'a\n\n',b'a\0b',b'X'*4097]:
            self.password.write_bytes(raw)
            with self.subTest(raw_size=len(raw)),self.assertRaises(ValueError):self.config()
        for raw in [b'NON_SECRET_TEST_SENTINEL',b'NON_SECRET_TEST_SENTINEL\n',b'NON_SECRET_TEST_SENTINEL\r\n']:
            self.password.write_bytes(raw);self.config()

    def test_environment_password_line_validation(self):
        for value in ['x\ny','x\ry','x\0y']:
            with self.assertRaises(ValueError):self.config(dict(KSPASS_FILE='',KSPASS=value))

    def sdk_fixture(self,args,env):
        args=[str(x) for x in args];self.calls.append(args)
        self.assertNotIn('NON_SECRET_TEST_SENTINEL',str(args))
        target=Path(args[-1] if Path(args[0]).name=='zipalign' else args[args.index('--out')+1])
        target.write_bytes(b'NOT_AN_APK_OR_SIGNATURE')

    def verify_fixture(self,apk,source,sdk,expected,allow_test):
        self.assertEqual(expected,'A'*64);self.assertFalse(allow_test)
        return dict(sha256=hashlib.sha256(Path(apk).read_bytes()).hexdigest().upper(),testSigningIdentity=False)

    def test_alignment_before_sdk_signing_then_full_verification(self):
        self.calls=[]
        with patch.dict(os.environ,self.env,clear=True),patch.object(signer,'sdk_run',side_effect=self.sdk_fixture),patch.object(signer,'verify',side_effect=self.verify_fixture) as verify:
            signer.sign(self.apk,self.source,self.output,self.root/'sdk')
        self.assertEqual(len(self.calls),2);self.assertEqual(Path(self.calls[0][0]).name,'zipalign')
        command=self.calls[1];self.assertEqual(Path(command[0]).name,'apksigner')
        self.assertEqual(command[command.index('--ks-key-alias')+1],'bttv-android')
        self.assertEqual(command[command.index('--ks-pass')+1],'file:'+str(self.password))
        self.assertNotIn('--key-pass',command) # Do not read a single-line file twice.
        self.assertEqual(command[command.index('--v3-signing-enabled')+1],'true')
        self.assertEqual(verify.call_count,1)
        self.assertTrue((self.output/'twitch.apk').is_file());self.assertTrue((self.output/'verification.json').is_file())
        self.assertFalse((self.output/'twitch.apk.part').exists())

    def test_signer_failure_cannot_export(self):
        with patch.dict(os.environ,self.env,clear=True),patch.object(signer,'sdk_run',side_effect=ValueError('controlled fixture failure')),patch.object(signer,'verify') as verify:
            with self.assertRaises(ValueError):signer.sign(self.apk,self.source,self.output,self.root/'sdk')
        self.assertFalse(self.output.exists());verify.assert_not_called()

    def test_verification_failure_cannot_export(self):
        self.calls=[]
        with patch.dict(os.environ,self.env,clear=True),patch.object(signer,'sdk_run',side_effect=self.sdk_fixture),patch.object(signer,'verify',side_effect=ValueError('controlled verification failure')):
            with self.assertRaises(ValueError):signer.sign(self.apk,self.source,self.output,self.root/'sdk')
        self.assertFalse(self.output.exists())

    def test_export_hash_mismatch_never_promotes_candidate(self):
        self.calls=[]
        with patch.dict(os.environ,self.env,clear=True),patch.object(signer,'sdk_run',side_effect=self.sdk_fixture),patch.object(signer,'verify',side_effect=self.verify_fixture),patch.object(signer,'sha256',return_value='B'*64):
            with self.assertRaises(ValueError):signer.sign(self.apk,self.source,self.output,self.root/'sdk')
        self.assertFalse((self.output/'twitch.apk').exists());self.assertFalse((self.output/'verification.json').exists())

    def test_existing_output_is_never_overwritten(self):
        self.output.mkdir()
        with patch.object(signer,'sdk_run') as sdk,self.assertRaises(ValueError):signer.sign(self.apk,self.source,self.output)
        sdk.assert_not_called()

    def test_sdk_output_is_captured_and_stdin_closed(self):
        result=subprocess.CompletedProcess([],1,stdout=b'NON_SECRET_TEST_SENTINEL')
        with patch.object(signer.subprocess,'run',return_value=result) as run:
            with self.assertRaises(ValueError) as error:signer.sdk_run(['SDK_FIXTURE_ONLY'],{})
        self.assertNotIn('NON_SECRET_TEST_SENTINEL',str(error.exception))
        self.assertEqual(run.call_args.kwargs['stdin'],subprocess.DEVNULL)
        self.assertEqual(run.call_args.kwargs['stdout'],subprocess.PIPE)

    def test_build_rejects_signing_inputs_before_any_work(self):
        for key in ['KS','KSPASS','KSPASS_FILE','KEYSTORE','KEYSTORE_BASE64']:
            with patch.dict(os.environ,{key:'NON_SECRET_TEST_SENTINEL'},clear=True),patch.object(builder,'inspect') as inspect:
                with self.assertRaises(ValueError):builder.build(self.source,self.root/'work',self.output,True)
                inspect.assert_not_called()

    def test_cli_failure_does_not_log_input_values(self):
        env=dict(os.environ,KS=str(self.key),KSPASS='NON_SECRET_TEST_SENTINEL',KSPASS_FILE='',EXPECTED_SIGNER_SHA256='invalid')
        result=subprocess.run([sys.executable,'-B',str(ROOT/'tools/sign_release.py'),
            '--apk',str(self.apk),'--input',str(self.source),'--output',str(self.output)],env=env,capture_output=True)
        self.assertNotEqual(result.returncode,0);self.assertFalse(self.output.exists())
        self.assertNotIn(b'NON_SECRET_TEST_SENTINEL',result.stdout+result.stderr)

    @unittest.skipUnless(os.name=='posix' and shutil.which('bash'),'Linux Bash guard; no build tools execute')
    def test_shell_rejects_private_inputs_before_any_build_tool(self):
        for key in ['KS','KSPASS','KSPASS_FILE','KEYSTORE','KEYSTORE_BASE64']:
            env=dict(PATH=os.environ['PATH'],**{key:'NON_SECRET_TEST_SENTINEL'})
            result=subprocess.run(['bash',str(ROOT/'build'),'nonexistent-decoded-tree'],cwd=self.root,env=env,capture_output=True)
            self.assertEqual(result.returncode,2);self.assertNotIn(b'NON_SECRET_TEST_SENTINEL',result.stdout+result.stderr)
        (self.root/'.env').write_text('KSPASS =NON_SECRET_TEST_SENTINEL\n')
        result=subprocess.run(['bash',str(ROOT/'build'),'nonexistent-decoded-tree'],cwd=self.root,env=dict(PATH=os.environ['PATH']),capture_output=True)
        self.assertEqual(result.returncode,2);self.assertNotIn(b'NON_SECRET_TEST_SENTINEL',result.stdout+result.stderr)

    def test_unsigned_output_is_not_a_verified_release(self):
        def stage(root,destination,additional):
            destination.mkdir()
            for relative in ['initworkspace','disassemble','buildsource','patch','build','mod/gradlew','tools/docker_build.sh']:
                p=destination/relative;p.parent.mkdir(parents=True,exist_ok=True);p.write_text('fixture only\r\n')
        def run(args,**kwargs):
            self.assertEqual(args,['bash','initworkspace']);self.assertEqual(kwargs['env']['BTTV_UNSIGNED_BUILD'],'1')
            for key in ['KS','KSPASS','KSPASS_FILE']:self.assertFalse(kwargs['env'].get(key))
            (kwargs['cwd']/'dist/twitch.apk').write_bytes(b'NOT_AN_APK')
        with patch.dict(os.environ,{},clear=True),patch.object(builder,'inspect'),patch.object(builder,'stage',side_effect=stage),patch.object(builder.subprocess,'run',side_effect=run):
            builder.build(self.source,self.root/'work',self.output,True)
        self.assertTrue((self.output/'unsigned.apk').exists());self.assertFalse((self.output/'twitch.apk').exists())
        self.assertTrue(json.loads((self.output/'unsigned.json').read_text())['unsigned'])
        self.assertFalse((self.output/'verification.json').exists())


class InfrastructureSecurity(unittest.TestCase):
    def setUp(self):
        self.ci=(ROOT/'.github/workflows/ci.yml').read_text()
        self.unsigned=self.ci.split('  unsigned_candidate:',1)[1].split('  signed_candidate:',1)[0]
        self.signed=self.ci.split('  signed_candidate:',1)[1]

    def test_manual_default_branch_opt_in_gates(self):
        gate="github.event_name == 'workflow_dispatch' && inputs.build_apk && vars.COMMUNITY_SIGNING_ENABLED == 'true' && github.ref == format('refs/heads/{0}', github.event.repository.default_branch)"
        for job in [self.unsigned,self.signed]:self.assertIn('    if: '+gate,job)
        self.assertNotIn("github.repository == 'bttv-android/bttv'",self.ci)
        self.assertEqual(self.ci.count("repository() == os.environ['GITHUB_REPOSITORY']"),2)

    def test_secrets_only_in_protected_signing_job(self):
        self.assertNotIn('secrets.',self.ci.split('  signed_candidate:',1)[0])
        self.assertIn('environment: community-release',self.signed)
        self.assertIn('needs: [checks, unsigned_candidate]',self.signed)
        self.assertNotIn('secrets.',(ROOT/'.github/workflows/docker.yml').read_text())
        self.assertEqual(self.ci.count('secrets.KEYSTORE'),1);self.assertEqual(self.ci.count('secrets.KSPASS'),1)

    def test_offline_signing_occurs_after_build_without_running_gradle(self):
        self.assertIn('--unsigned',self.unsigned);self.assertNotIn('KSPASS',self.unsigned)
        self.assertLess(self.signed.index('Prepare SDK toolchain'),self.signed.index('Materialize protected'))
        command=self.signed.split('      - name: Offline private signing',1)[1].split('      - name:',1)[0]
        for expected in ['--network none','--read-only','target=/run/keystore.p12,readonly','target=/run/password,readonly','/source/tools/sign_release.py']:
            self.assertIn(expected,command)
        self.assertNotIn('-e KSPASS ',command);self.assertNotIn('build_production.py',command)

    def test_fixed_commit_artifact_and_no_publication_permissions(self):
        self.assertEqual(self.ci.count('ref: ${{ github.sha }}'),2)
        self.assertIn('contents: read',self.ci)
        for text in [self.ci,(ROOT/'.github/workflows/docker.yml').read_text()]:
            for bad in ['pull_request_target','contents: write','secrets: inherit','git push','gh release','actions/create-release']:
                self.assertNotIn(bad,text)
            actions=re.findall(r'uses: ([^\s#]+)',text)
            self.assertTrue(actions)
            for action in actions:self.assertRegex(action,r'^actions/[a-z-]+@[0-9a-f]{40}$')
        self.assertNotIn('run-id:',self.signed);self.assertNotIn('github-token:',self.signed)

    def test_cleanup_precedes_verified_artifact_upload(self):
        self.assertIn('if: always()',self.signed)
        self.assertLess(self.signed.index('Remove runner signing inputs'),self.signed.index('uses: actions/upload-artifact'))
        self.assertIn('dist/candidate/build/verification.json',self.signed)
        upload=self.signed.split('uses: actions/upload-artifact',1)[1]
        self.assertNotIn('build.log',upload);self.assertNotIn('path: dist/',upload)

    def test_inline_python_is_syntactically_valid_without_execution(self):
        scripts=re.findall(r"          python3 - <<'PY'\n(.*?)          PY",self.ci,re.S)
        self.assertGreaterEqual(len(scripts),4)
        for body in scripts:ast.parse('\n'.join(line[10:] for line in body.splitlines()))

    def test_release_verifier_and_metadata_contract_unchanged(self):
        for path in ['tools/verify_release_apk.py','tools/release_metadata.py','bttv.manifest.json','mod/app/src/main/java/bttv/updater/UpdateVerifier.java']:
            baseline=subprocess.check_output(['git','show','86a6d791b2ed76a9994e34bcb1549ace5516ce54:'+path],cwd=ROOT)
            if path=='bttv.manifest.json':
                # Only the explicitly approved APK A metadata differs; security code stays exact.
                baseline=baseline.replace(b'0.43.2-beta',b'0.44.0-beta').replace(b'01208000338',b'1208000339')
            self.assertEqual((ROOT/path).read_bytes().replace(b'\r\n',b'\n'),baseline.replace(b'\r\n',b'\n'),path)


